//! Per-package egress: which dependency may reach the network under the build jail.
//!
//! # The defense is PACKAGE IDENTITY, not host granularity
//!
//! This is the load-bearing premise and it is easy to get backwards. The attack the build
//! jail exists to blunt is the one Shai-Hulud used: an attacker publishes a new `postinstall`
//! into a package that never had one, and it runs with the user's full access. The package is
//! not one anybody vetted for network use — it is `chalk`, or whatever the worm reached.
//!
//! So the control that matters is the ENTRY, not the hostname. A package with no entry in
//! `data/build-jail-catalog.json` gets no egress, whatever hosts it asks for, and a package
//! that needs egress has to arrive through a pull request against that file first. That PR is
//! the whole opt-in mechanism.
//!
//! # Which is why egress is a BOOLEAN
//!
//! It follows that host granularity buys much less than it appears to. Narrowing an admitted
//! host to a per-package subset constrains a package somebody already reviewed and trusted; it
//! does nothing about the unvetted package, which is the actual threat. It also could not be
//! made to hold: the measured redirect chains alone break it — a `github.com` release asset is
//! a 302 to `release-assets.githubusercontent.com`, an `/archive/` URL a 302 to
//! `codeload.github.com` — so a per-package host list is a list of the hosts a package was
//! seen to ASK for, never the set it must reach.
//!
//! The catalog's per-package `hosts` is therefore EVIDENCE and not enforcement. It is kept
//! structured per package rather than dropped into prose for one reason: **a changing host
//! list is a detection signal.** A package that used to fetch from its own CDN and now reaches
//! somewhere else shows up as a diff in a pull request, which is the Shai-Hulud tell, and
//! prose does not diff usefully. It is also the only answer to the question `network: true`
//! raises — "to where?" — which cannot be read off the code.

// THE TABLE IS DATA, NOT CODE. Generated by `build.rs` from the catalog's `network` field.
include!(concat!(env!("OUT_DIR"), "/package_network.rs"));

/// May `package_name`'s lifecycle script reach the network?
///
/// `None` — aube withheld the installer-resolved identity because its root is a checkout it
/// FETCHED — is `false`, the conservative direction and the same reading the curated
/// filesystem table takes.
pub fn network_granted(package_name: Option<&str>) -> bool {
    package_name.is_some_and(|name| NETWORK_GRANTED.contains(&name))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The authorship invariant, same as the curated filesystem table's: the key is the name
    /// the RESOLVER assigned, and the lookup is exact, so a package cannot rename itself into
    /// an entry. `None` matches nothing.
    #[test]
    fn only_an_exact_installer_resolved_name_matches() {
        assert!(network_granted(Some("node-libcurl")), "the control");
        assert!(!network_granted(None));
        for impostor in ["node-libcurl-x", "x-node-libcurl", "Node-LibCurl"] {
            assert!(
                !network_granted(Some(impostor)),
                "{impostor} must not match a real entry"
            );
        }
    }

    /// The table has to actually cover the ecosystem it claims to, or the model above is
    /// describing an empty set. The corpus found 146 network-needing packages; two more carry
    /// egress with no resolvable host (`hasura-cli`'s `dist/` is absent from its own published
    /// tarball, `redis-memory-server` assembles its URL across compiled modules), and
    /// `install-peers` is excluded because its egress was measured UNREACHABLE under nub.
    #[test]
    fn the_table_covers_the_corpus_network_cohort() {
        assert!(
            NETWORK_GRANTED.len() >= 145,
            "only {} packages carry an egress grant; the corpus measured 146 that need one, so \
             the table has lost coverage",
            NETWORK_GRANTED.len()
        );
    }
}
