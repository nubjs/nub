//! The project/dependency boundary for the `nub.jsonc` `loader` map.
//!
//! A project's `loader` configures the PROJECT's own source. It must not reach code
//! the project didn't write — without a node_modules gate, `{"loader": {".json":
//! "text"}}` silently turned every dependency's JSON import into a string. Nub's
//! BUILT-IN data loaders (`.jsonc`/`.json5`/`.toml`/`.yaml`/`.yml`/`.txt`) are a
//! runtime feature rather than a project setting, so they keep serving dependencies.
//! Both halves are pinned here, in one run, over both kinds of `loader` entry: one
//! that OVERRIDES a built-in extension (`.yaml` → text) and one that ADDS an
//! extension Nub has no built-in for (`.conf` → toml).
//!
//! Data parsing needs the nub-native addon (the npm yaml/toml parser fallback is not
//! a dev dep) — the same prerequisite as integration.rs's `data_format_loaders`.

use std::path::{Path, PathBuf};
use std::process::Command;

fn nub_binary() -> PathBuf {
    PathBuf::from(env!("CARGO_BIN_EXE_nub"))
}

fn write(path: &Path, contents: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, contents).unwrap();
}

/// A project whose `loader` config both overrides a built-in extension and adds a new
/// one, with a dependency that imports the same two extensions.
fn fixture() -> (tempfile::TempDir, PathBuf) {
    let temp = tempfile::tempdir().unwrap();
    let project = temp.path().join("project");
    let dep = project.join("node_modules/dep");

    write(
        &project.join("nub.jsonc"),
        r#"{ "loader": { ".yaml": "text", ".conf": "toml" } }"#,
    );
    write(
        &project.join("package.json"),
        r#"{ "type": "module", "dependencies": { "dep": "*" } }"#,
    );
    write(&project.join("first.yaml"), "host: first\n");
    write(&project.join("app.conf"), "title = \"app\"\n");
    write(
        &project.join("main.mjs"),
        r#"import first from './first.yaml';
import conf from './app.conf';
import dep from 'dep';
console.log(JSON.stringify({
  first,
  confTitle: conf.title,
  depYaml: dep.yaml,
  depConfError: dep.confError,
}));
"#,
    );

    write(
        &dep.join("package.json"),
        r#"{ "name": "dep", "type": "module", "main": "index.mjs" }"#,
    );
    write(&dep.join("data.yaml"), "host: dep\n");
    write(&dep.join("data.conf"), "title = \"dep\"\n");
    // The `.conf` import is dynamic so its failure is observable in-band: the project
    // taught Nub `.conf`, the dependency did not, so Node must reject the extension
    // exactly as it would with no nub.jsonc present.
    write(
        &dep.join("index.mjs"),
        r#"import yaml from './data.yaml';
let confError = null;
try {
  await import('./data.conf');
} catch (err) {
  confError = err?.code ?? String(err);
}
export default { yaml, confError };
"#,
    );

    (temp, project)
}

#[test]
fn project_loader_config_stops_at_the_node_modules_boundary() {
    let (temp, project) = fixture();
    let output = Command::new(nub_binary())
        .arg("main.mjs")
        .current_dir(&project)
        .env("XDG_CONFIG_HOME", temp.path().join("config"))
        .env("XDG_CACHE_HOME", temp.path().join("cache"))
        .output()
        .unwrap();
    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();
    assert!(
        output.status.success(),
        "run failed ({:?})\nstdout: {stdout}\nstderr: {stderr}",
        output.status.code()
    );
    let value: serde_json::Value = serde_json::from_str(stdout.trim())
        .unwrap_or_else(|e| panic!("stdout is not the probe's JSON ({e})\nstdout: {stdout}"));

    assert_eq!(
        value["first"], "host: first\n",
        "the project's `.yaml`->text override must apply to project source: {value}"
    );
    assert_eq!(
        value["confTitle"], "app",
        "the project's added `.conf`->toml loader must apply to project source: {value}"
    );
    assert_eq!(
        value["depYaml"]["host"], "dep",
        "a dependency's `.yaml` must stay on Nub's BUILT-IN yaml loader — the project's \
         `.yaml`->text override must not reach it (a leaked override yields the raw \
         string \"host: dep\\n\" instead of an object): {value}"
    );
    assert_eq!(
        value["depConfError"], "ERR_UNKNOWN_FILE_EXTENSION",
        "the project's added `.conf` loader must not teach Node a new extension inside \
         a dependency; the dependency's import must fail exactly as it would with no \
         nub.jsonc present (null here means the loader leaked and parsed it): {value}"
    );
}
