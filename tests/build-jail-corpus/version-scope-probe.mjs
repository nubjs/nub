#!/usr/bin/env node
// version-scope-probe.mjs — the INVERTED-RANGE control for a version-scoped catalog entry.
//
// WHY AN INVERTED RANGE AND NOT A BEFORE/AFTER. A 2x2 of "granted vs ungranted" at one
// version only proves the CAPABILITY is what the package needs; it says nothing about
// whether the semver range is the thing deciding, so a scope that never matched — a typo,
// a prerelease that no comparator reaches, a field the compiler ignores — would look
// identical to a scope that works. Running the SAME version against the SAME entry with
// the range INVERTED is what separates them: one catalog admits it, the other withholds
// it, and nothing else differs by a byte.
//
// This is the evidence shape the esbuild `<0.13.0` entry was landed on. Each arm asserts
// the override banner, because a rejected catalog falls back to the compiled one silently
// and produces a confident null result — hit twice while building this file, once because
// an `observed` field said "probe" and the validator (correctly) refused a placeholder.
//
//   node version-scope-probe.mjs --spec probes.json [--out DIR]
//
// probes.json: [{ package, version, range, entry: {…catalog entry minus package/versions} }]
//   `range`   the range under test. The arm labelled `scoped` uses it verbatim; the arm
//             labelled `inverted` uses `invert(range)`, and `ungranted` drops the entry.
// Env: NUB_BIN (required, built with --features build-jail-catalog-override).
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';

const argv = process.argv.slice(2);
const arg = (n, d) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : d; };
const NUB = process.env.NUB_BIN;
if (!NUB || !fs.existsSync(NUB)) { console.error('set NUB_BIN'); process.exit(2); }
const HARNESS = path.dirname(new URL(import.meta.url).pathname);
const BASE = JSON.parse(fs.readFileSync(process.env.BASE_CATALOG || path.join(HARNESS, '../../crates/nub-sandbox/data/build-jail-catalog.json'), 'utf8'));
const ROOT = arg('--out', path.join(os.homedir(), '.cache/nub/scope-probe'));
const STORE = path.join(os.homedir(), '.cache/nub/vspread/store');
const spec = JSON.parse(fs.readFileSync(arg('--spec'), 'utf8'));
const slug = (s) => s.replace(/[^A-Za-z0-9]+/g, '-');

// Only the two shapes this study produced. Deliberately not a general semver inverter:
// a wrong inversion would silently weaken the control, and the two forms in use are
// simple enough to invert by construction.
function invert(range) {
  const one = /^<(\d+\.\d+\.\d+)$/.exec(range);
  if (one) return `>=${one[1]}`;
  const win = /^>=(\d+\.\d+\.\d+), *<(\d+\.\d+\.\d+)$/.exec(range);
  if (win) return `<${win[1]}`;
  throw new Error(`no inversion defined for range '${range}'`);
}

// The provisioning the corpus manifests owe a package; without its input a script exits 0
// having done nothing and every arm "passes", which would invert the control's meaning.
function provision(proj, need, nonce) {
  if (need === 'nx-json') fs.writeFileSync(path.join(proj, 'nx.json'), '{ "affected": { "defaultBase": "main" } }\n');
  if (need === 'git-repo') { const g = (...a) => spawnSync('git', ['-C', proj, ...a]); g('init', '-q'); g('config', 'user.email', 'p@e.com'); g('config', 'user.name', 'p'); g('commit', '-qm', nonce, '--allow-empty'); }
}

function run(p, arm, versionsField) {
  const c = JSON.parse(JSON.stringify(BASE));
  c.packageNetwork.full = c.packageNetwork.full.filter((e) => e.package !== p.package);
  for (const h of c.networkHosts || []) if (h.fetchedBy) h.fetchedBy = h.fetchedBy.filter((n) => n !== p.package);
  c.packageGrants = c.packageGrants.filter((e) => e.package !== p.package);
  if (versionsField !== null) {
    const observed = `Inverted-range control arm "${arm}" for ${p.package}@${p.version}; generated by version-scope-probe.mjs, never a shipped entry.`;
    const entry = { package: p.package, versions: versionsField, evidence: 'measured', observed, platform: 'macos-arm64', ...p.entry };
    if (p.entry.projectReads || p.entry.projectWrites || p.entry.projectCwd) c.packageGrants.push(entry);
    else c.packageNetwork.full.push(entry);
  }
  const nonce = `N${Date.now().toString(36)}${Math.floor(Math.random() * 1e6).toString(36)}`;
  const dir = path.join(ROOT, `${slug(p.package)}-${slug(p.version)}-${arm}`);
  const proj = path.join(dir, 'proj'), home = path.join(dir, 'home'), tmp = path.join(dir, 'tmp');
  fs.rmSync(dir, { recursive: true, force: true });
  for (const d of [proj, home, tmp]) fs.mkdirSync(d, { recursive: true });
  const cat = path.join(dir, 'catalog.json');
  fs.writeFileSync(cat, JSON.stringify(c, null, 2));
  fs.writeFileSync(path.join(proj, 'package.json'), JSON.stringify({ name: `sp-${nonce}`, version: '1.0.0', private: true, dependencies: { [p.package]: p.version } }, null, 2));
  provision(proj, p.need, nonce);
  fs.writeFileSync(path.join(proj, '.npmrc'), 'minimumReleaseAge=0\nminimumReleaseAgeStrict=false\nside-effects-cache=false\n');
  const env = { PATH: '/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin', HOME: home, TMPDIR: tmp, NUB_CACHE_DIR: STORE, NUB_BUILD_JAIL_CATALOG: cat };
  const o = { cwd: proj, env, encoding: 'utf8', timeout: 900_000, maxBuffer: 64 << 20 };
  const inst = spawnSync(NUB, ['install'], o);
  if (inst.status !== 0) { fs.rmSync(dir, { recursive: true, force: true }); return { arm, rc: null, note: 'INSTALL-FAILED' }; }
  const w = spawnSync(NUB, ['approve-builds', p.package], o);
  const out = (w.stdout || '') + (w.stderr || '');
  const banner = /build-jail catalog OVERRIDDEN[^\n]*\(([^)]*)\)/.exec(out);
  const empty = /No ignored builds to approve/.test(out);
  fs.rmSync(dir, { recursive: true, force: true });
  return { arm, rc: w.status, banner: banner ? banner[1] : null, note: !banner ? 'CATALOG NOT LOADED — arm is void' : empty ? 'EMPTY WINDOW — arm is void' : '' };
}

let bad = 0;
for (const p of spec) {
  const arms = [run(p, 'scoped', p.range), run(p, 'inverted', invert(p.range)), run(p, 'ungranted', null)];
  console.log(`\n${p.package}@${p.version}   range under test: ${p.range}   inverted: ${invert(p.range)}`);
  for (const a of arms) console.log(`  ${a.arm.padEnd(10)} rc=${String(a.rc).padEnd(5)} banner=(${a.banner ?? 'NONE'}) ${a.note}`);
  const [s, i, u] = arms;
  const ok = arms.every((a) => !a.note) && s.rc === 0 && i.rc !== 0 && u.rc !== 0;
  console.log(`  => ${ok ? 'CONTROL HOLDS: the RANGE decides (scoped passes, inverted and ungranted both fail)' : 'CONTROL DOES NOT HOLD — do not land this scope'}`);
  if (!ok) bad++;
}
process.exit(bad ? 1 : 0);
